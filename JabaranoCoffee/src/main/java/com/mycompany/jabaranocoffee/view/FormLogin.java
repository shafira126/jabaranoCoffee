    // Input
    private String getInputUsername() {
        return txtUsername.getText().trim();
    }

    private String getInputPassword() {
        return new String(txtPassword.getPassword()).trim();
    }
    
    // Proses: validasi dan login
    // ----------------------------------------------------------------
    private void doLogin() {
        String username = getInputUsername();
        String password = getInputPassword();

        if (username.isEmpty() || password.isEmpty()) {
            showError("Username dan password tidak boleh kosong.");
            return;
        }

        lblError.setText("");

        User user = userRepository.login(username, password);

        if (user != null) {
            openDashboard(user);
        } else {
            showError("Username atau password salah.");
            txtPassword.setText("");
            txtUsername.requestFocus();
        }
    }
    
    // Output: navigasi ke FormDashboard
    // ----------------------------------------------------------------
    private void openDashboard(User user) {
        // Uncomment setelah FormDashboard selesai dikerjakan Rangga:
        // new FormDashboard(user).setVisible(true);
        // this.dispose();

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Login berhasil! Selamat datang, " + user.getUsername() + ".",
            "Berhasil",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
        );
    }
    
    // Helper
    // ----------------------------------------------------------------
